#!/usr/bin/env node
/**
 * Writes src/constants/api-enums.generated.ts from the string enums in the OpenAPI snapshot
 * (src/types/api.openapi.json, `components.schemas`). The API lists them once, in peanut-api-ts
 * src/wire/enums.ts; the weekday sync-openapi PR carries a change here. Runs as part of
 * `pnpm gen:api`; `pnpm check:api` fails when the committed file differs from a fresh run.
 *
 *   node scripts/generate-api-enums.mjs           write the file
 *   node scripts/generate-api-enums.mjs --print   print it (used by check-api-enum-copies)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const SNAPSHOT = resolve(ROOT, 'src/types/api.openapi.json')
const OUTPUT = resolve(ROOT, 'src/constants/api-enums.generated.ts')

/** name → values for every `{ type: 'string', enum: [...] }` component schema. */
export function readApiEnums(snapshotPath = SNAPSHOT) {
    const spec = JSON.parse(readFileSync(snapshotPath, 'utf8'))
    const schemas = spec.components?.schemas ?? {}
    return Object.fromEntries(
        Object.entries(schemas)
            .filter(([, schema]) => schema?.type === 'string' && Array.isArray(schema.enum))
            .sort(([a], [b]) => a.localeCompare(b))
            .map(([name, schema]) => [name, schema.enum])
    )
}

const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/

export function renderApiEnums(enums) {
    const blocks = Object.entries(enums).map(([name, values]) => {
        for (const value of [name, ...values]) {
            if (!IDENTIFIER.test(value)) throw new Error(`api enum ${name}: not an identifier: ${value}`)
        }
        return [
            `export const ${name} = {`,
            ...values.map((value) => `    ${value}: '${value}',`),
            '} as const',
            `export type ${name} = (typeof ${name})[keyof typeof ${name}]`,
        ].join('\n')
    })
    return [
        '// Generated by scripts/generate-api-enums.mjs from src/types/api.openapi.json. Do not edit.',
        '// Source of truth: peanut-api-ts src/wire/enums.ts. Regenerate with `pnpm gen:api`.',
        '',
        blocks.join('\n\n'),
        '',
    ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const text = renderApiEnums(readApiEnums())
    if (process.argv.includes('--print')) process.stdout.write(text)
    else writeFileSync(OUTPUT, text)
}
