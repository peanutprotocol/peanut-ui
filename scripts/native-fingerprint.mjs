#!/usr/bin/env node
// Hashes the JS<->native contract, so an OTA can tell whether the bundle it is
// about to publish still fits the binaries that will receive it.
//
// The problem this closes: JS and native ship on two independent clocks, and a
// bundle's only identity is a version number, which says nothing about the
// native surface it needs. `1.2.1` does not encode "requires the 8.51 updater
// plugin", so CI will happily publish a bundle built against new plugins onto
// binaries built months earlier, and the mismatch first appears on a user's
// device. Capgo's own `min_update_version` only blocks *delivery*, only under
// the `metadata` channel strategy, and lives in a dashboard CI cannot see — it
// never tells you that you built an incompatible bundle.
//
// The fingerprint is a pure function of the repo tree, so it needs no storage:
// a native release's surface is exactly what its tagged commit describes. The
// OTA lane compares the tree it is publishing against the newest
// `v<major>.<build>.0` tag and refuses when they disagree, naming what moved.
// That is the rule docs/NATIVE-RELEASE.md already states ("bump the native
// version whenever you change plugins/native code") with something checking it.
//
// Three kinds of input, because the contract has three parts and each has its
// own way of going stale:
//
//   file   Native config the JS half can observe — permissions, entitlements,
//          deployment floors, the Capacitor runtime config.
//   glob   The in-repo native bridges themselves: the Java/Kotlin and Swift
//          plugins JS actually calls. A bundle that calls a new method on
//          PushProvisioningPlugin needs the binary that has it.
//   deps   Native plugin versions resolved from pnpm-lock.yaml. The generated
//          Capacitor manifests are committed but NOT regenerated by the OTA
//          workflow, so a plugin bumped in package.json + the lockfile without
//          a `cap sync` leaves them stale: `pnpm install` still hands the new
//          JS wrapper to the bundle while the manifests read unchanged. The
//          lockfile is the authoritative record of the wrapper being shipped.
//
// Generated web assets (ios/App/App/public, android/app/src/main/assets/public)
// are excluded on purpose — they are OTA output, and including them would
// change the fingerprint on every commit.
//
// Usage:
//   node scripts/native-fingerprint.mjs                 # hash of the working tree
//   node scripts/native-fingerprint.mjs --ref v1.2.0    # hash at a git ref
//   node scripts/native-fingerprint.mjs --manifest      # per-input hashes as JSON
//   node scripts/native-fingerprint.mjs --diff v1.2.0   # what moved; exit 1 if anything did

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// Dependencies with a native half. The generated Capacitor manifests already
// list the plugin SET, so this exists to catch a version bump that never made
// it through `cap sync` — the two are deliberately redundant.
const NATIVE_DEPENDENCY_PATTERN = /^(@capacitor\/|@capgo\/|@onesignal\/|@sumsub\/)|cordova/

// Every input is one line of the manifest. Adding one is a deliberate act: it
// widens what counts as "the native surface changed" and therefore how often an
// OTA is refused, so prefer the narrowest input that actually carries the
// contract over the directory that contains it.
export const NATIVE_INPUTS = [
    // Capacitor's generated plugin manifests — the plugin set and their exact
    // resolved versions, per platform.
    { kind: 'file', id: 'android/capacitor.settings.gradle' },
    { kind: 'file', id: 'ios/App/CapApp-SPM/Package.swift' },

    // Native runtime config the JS half reads through the bridge.
    { kind: 'file', id: 'capacitor.config.ts' },

    // Android build surface: dependencies, SDK levels, permissions.
    { kind: 'file', id: 'android/build.gradle' },
    { kind: 'file', id: 'android/app/build.gradle' },
    { kind: 'file', id: 'android/variables.gradle' },
    { kind: 'file', id: 'android/app/src/main/AndroidManifest.xml' },

    // iOS build surface: targets, deployment floor, capabilities.
    { kind: 'file', id: 'ios/App/App.xcodeproj/project.pbxproj' },
    { kind: 'file', id: 'ios/App/App/Info.plist' },
    { kind: 'file', id: 'ios/App/App/App.entitlements' },
    { kind: 'file', id: 'ios/App/App/AppRelease.entitlements' },

    // The bridges JS calls into. MainActivity registers the app-local plugins;
    // the *Plugin.java / *Plugin.swift files are the methods themselves. A
    // bundle calling a new method, or relying on corrected behaviour in one of
    // these, needs the binary that carries it — and none of the config files
    // above move when they change.
    { kind: 'glob', id: 'android/app/src/**.{java,kt}', dirs: ['android/app/src'], extensions: ['.java', '.kt'] },
    { kind: 'glob', id: 'ios/App/**.swift', dirs: ['ios/App'], extensions: ['.swift'] },

    // Resolved native plugin versions, from the lockfile rather than the
    // generated manifests, which the OTA workflow never regenerates.
    { kind: 'deps', id: 'native-plugin-versions' },
]

// A file the tree does not have is still a fact about the surface — adding or
// deleting one must move the fingerprint — so absence gets its own sentinel
// rather than being skipped.
const ABSENT = '<absent>'

/*
 * project.pbxproj carries MARKETING_VERSION, which scripts/native-ios-postsync.js
 * stamps from the release version on every `cap sync`. That is the release
 * number, not the native surface: left raw it would change the fingerprint on
 * every single release and make the check cry wolf forever. CURRENT_PROJECT_VERSION
 * is the CI run number and is normalised for the same reason.
 */
function normalize(path, content) {
    if (!path.endsWith('project.pbxproj')) return content
    return content
        .replace(/MARKETING_VERSION = [^;]*;/g, 'MARKETING_VERSION = <normalized>;')
        .replace(/CURRENT_PROJECT_VERSION = [^;]*;/g, 'CURRENT_PROJECT_VERSION = <normalized>;')
}

function git(args) {
    return execFileSync('git', args, {
        cwd: repoRoot,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
        maxBuffer: 64 * 1024 * 1024,
    })
}

function readAtRef(path, ref) {
    if (!ref) {
        try {
            return readFileSync(resolve(repoRoot, path), 'utf8')
        } catch (err) {
            if (err.code === 'ENOENT') return null
            throw err
        }
    }
    try {
        // `git show` exits non-zero for a missing path, which is how absence is
        // detected at a ref.
        return git(['show', `${ref}:${path}`])
    } catch {
        return null
    }
}

/*
 * Sorted, so the digest never depends on filesystem or git enumeration order.
 *
 * Directory prefixes + an extension filter applied HERE, deliberately not a
 * `**` glob pathspec: `git ls-tree -r -- 'android/app/src/**\/*.java'` matches
 * nothing and exits 0, so every ref would have reported an empty bridge set and
 * the check would have silently compared nothing against nothing.
 */
function listFiles({ dirs, extensions }, ref) {
    const args = ref
        ? ['ls-tree', '-r', '--name-only', ref, '--', ...dirs]
        : ['ls-files', '--cached', '--others', '--exclude-standard', '--', ...dirs]
    let paths
    try {
        paths = git(args).split('\n').filter(Boolean)
    } catch {
        return []
    }
    return paths.filter((path) => extensions.some((extension) => path.endsWith(extension))).sort()
}

function sha(text) {
    return createHash('sha256').update(text).digest('hex')
}

// Every native dependency's resolved version(s), read from the lockfile. Names
// come from package.json so the set is explicit; versions come from the
// lockfile so a bump cannot hide behind a caret specifier.
function nativeDependencyVersions(ref) {
    const packageJson = readAtRef('package.json', ref)
    const lockfile = readAtRef('pnpm-lock.yaml', ref)
    if (!packageJson || !lockfile) return null

    let parsed
    try {
        parsed = JSON.parse(packageJson)
    } catch {
        return null
    }

    const names = Object.keys({ ...parsed.dependencies, ...parsed.devDependencies })
        .filter((name) => NATIVE_DEPENDENCY_PATTERN.test(name))
        .sort()

    return names
        .map((name) => {
            const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
            // Lockfile keys look like `'@capgo/capacitor-updater@8.51.14(@capacitor/core@8.2.0)':`,
            // so the same name also appears inside peer suffixes — collecting
            // every distinct version it resolves to is exactly what we want.
            const versions = new Set()
            for (const match of lockfile.matchAll(new RegExp(`${escaped}@(\\d[^\\s'":()]*)`, 'g'))) {
                versions.add(match[1])
            }
            return `${name}@${[...versions].sort().join(',') || '<unresolved>'}`
        })
        .join('\n')
}

export function manifest(ref) {
    const entries = {}
    for (const input of NATIVE_INPUTS) {
        if (input.kind === 'file') {
            const raw = readAtRef(input.id, ref)
            entries[input.id] = raw === null ? ABSENT : sha(normalize(input.id, raw))
            continue
        }

        if (input.kind === 'glob') {
            const files = listFiles(input, ref)
            if (files.length === 0) {
                entries[input.id] = ABSENT
                continue
            }
            // Path AND content: a rename with identical bytes still changes the
            // set of classes the binary carries.
            const parts = files.map((path) => {
                const raw = readAtRef(path, ref)
                return `${path}:${raw === null ? ABSENT : sha(raw)}`
            })
            entries[input.id] = sha(parts.join('\n'))
            continue
        }

        const versions = nativeDependencyVersions(ref)
        entries[input.id] = versions === null ? ABSENT : sha(versions)
    }
    return entries
}

// Hash of the manifest, not of the concatenated inputs: the per-input digests
// are what a diff reports, so the summary hash must be derived from exactly
// what the diff inspects or the two could disagree.
export function fingerprint(ref) {
    const entries = manifest(ref)
    const canonical = NATIVE_INPUTS.map((input) => `${input.id}:${entries[input.id]}`).join('\n')
    return sha(canonical).slice(0, 16)
}

export function diff(baseRef, headRef) {
    const base = manifest(baseRef)
    const head = manifest(headRef)
    return NATIVE_INPUTS.filter((input) => base[input.id] !== head[input.id]).map((input) => ({
        path: input.id,
        base: base[input.id],
        head: head[input.id],
    }))
}

function flag(argv, name) {
    const index = argv.indexOf(name)
    return index === -1 ? undefined : argv[index + 1]
}

function main(argv) {
    const ref = flag(argv, '--ref')

    if (argv.includes('--manifest')) {
        return JSON.stringify(manifest(ref), null, 2)
    }

    // Presence of the flag decides the mode, never the value it picked up: a
    // trailing `--diff` reads as "compare against nothing", and silently
    // printing a fingerprint instead would let a misconfigured workflow step
    // pass while checking nothing at all.
    if (argv.includes('--diff')) {
        const against = flag(argv, '--diff')
        if (!against) throw new Error('--diff needs a git ref to compare against')
        const changed = diff(against, ref)
        if (changed.length === 0) {
            return `native surface unchanged since ${against} (${fingerprint(against)})`
        }
        const lines = changed.map(({ path, base, head }) => {
            const describe = (value) => (value === ABSENT ? 'absent' : value.slice(0, 12))
            return `  ${path}: ${describe(base)} -> ${describe(head)}`
        })
        process.stdout.write(
            `native surface changed since ${against}: ${fingerprint(against)} -> ${fingerprint(ref)}\n` +
                `${lines.join('\n')}\n`
        )
        process.exit(1)
    }

    return fingerprint(ref)
}

// Only run as a CLI; the exports above are what the tests use.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
    try {
        process.stdout.write(`${main(process.argv.slice(2))}\n`)
    } catch (err) {
        console.error(`✗ native-fingerprint: ${err.message}`)
        process.exit(1)
    }
}
