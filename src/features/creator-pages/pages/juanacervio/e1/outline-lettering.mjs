// Writes lettering-outlines.ts: the poster lettering of Nita's page E1 as glyph outlines.
// Run it after a change to the headline in nita-e1.copy.ts, one argument per line of the headline:
//   node src/features/creator-pages/pages/juanacervio/e1/outline-lettering.mjs "Cobrá de" "afuera en" "USD y EUR"
// fontkit is not a direct dependency; it comes with @react-pdf/renderer, so the path goes through pnpm's store.
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '../../../../../..')
const fontkit = createRequire(join(root, 'node_modules/.pnpm/node_modules/'))('fontkit')

const EM = 1000
// The same tracking the page's condensed HTML caps use (letter-spacing: 0.01em).
const TRACKING = 0.01 * EM

const font = fontkit.openSync(join(root, 'src/assets/fonts/roboto-flex-bold.woff2'))
// fontkit's getVariation() cannot re-read a compressed WOFF2, so the weight is set on the opened font, whose only
// axis is wght. Reading one glyph first makes fontkit unpack the WOFF2 glyph table, which fails once a weight is set.
font.getGlyph(0)
font.variationCoords = [1000]
const scale = EM / font.unitsPerEm
const point = (x, y, originX) => `${Math.round((originX + x) * scale)} ${Math.round(-y * scale)}`
const LETTERS = { moveTo: 'M', lineTo: 'L', quadraticCurveTo: 'Q', bezierCurveTo: 'C', closePath: 'Z' }

function outline(text) {
    const run = font.layout(text.toLocaleUpperCase('es'))
    let penX = 0
    let top = 0
    let d = ''
    run.glyphs.forEach((glyph, index) => {
        const { xAdvance, xOffset, yOffset } = run.positions[index]
        for (const { command, args } of glyph.path.commands) {
            d += LETTERS[command]
            for (let i = 0; i < args.length; i += 2) {
                d += (i ? ' ' : '') + point(args[i] + xOffset, args[i + 1] + yOffset, penX)
            }
        }
        top = Math.max(top, glyph.bbox.maxY + yOffset)
        penX += xAdvance + TRACKING / scale
    })
    return { d, advance: Math.round((penX - TRACKING / scale) * scale), top: Math.round(top * scale) }
}

const texts = process.argv.slice(2)
if (!texts.length) throw new Error('Pass the lines to outline as arguments.')

const entries = texts.map((text) => {
    const { d, advance, top } = outline(text)
    return `    '${text}': {\n        advance: ${advance},\n        top: ${top},\n        d: '${d}',\n    },`
})

writeFileSync(
    join(here, 'lettering-outlines.ts'),
    `// Generated by outline-lettering.mjs; do not edit. Roboto Flex at weight 1000, upper case, in a
// ${EM}-unit em with the baseline at y = 0 and y pointing down. \`advance\` is the width of the line,
// \`top\` how far its tallest glyph rises above the baseline (an accented capital is taller than a plain one).
export const E1_LETTERING_OUTLINES = {
${entries.join('\n')}
} as const

export type E1LetteringText = keyof typeof E1_LETTERING_OUTLINES
`
)
